"""Map the approved original plant pixels to black, red or transparency.

No generation, tracing, warping, white ink, soft alpha or lossy compression.
Requires Pillow. Run from any directory; --check verifies existing exports.
"""

from pathlib import Path
from collections import Counter
import hashlib
import json
import sys

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "docs/brand/source/coffee-branch-original.png"
ASSETS = ROOT / "sites/share/assets"
STUDIO = ROOT / "apps/web/public"
STUDIO_ICONS = [(32, "favicon-32x32.png"), (180, "apple-touch-icon.png"),
                (192, "tan-studio-192.png"), (512, "tan-studio-512.png")]
ICO_SIZES = [16, 32, 48, 64]
# Jar-label artwork embeds the plant as two ink layers so print separation can
# put black and Tan Red on their own planes. 432 px spans 18 mm at ~600 dpi.
LABEL_LOGO = ROOT / "apps/web/src/lib/labels/logo.ts"
LABEL_LOGO_WIDTH = 432
RED = (182, 21, 27)
ALLOWED = {(0, 0, 0, 0), (0, 0, 0, 255), (*RED, 255)}


def mapped_index(pixel):
    r, g, b, a = pixel
    if a < 128:
        return 0
    # Cherries and existing red registration marks retain their source position.
    if r >= 80 and r - g >= 35 and r - b >= 25 and r > 1.35 * g and r > 1.35 * b:
        return 2
    # Pale veins, highlights and paper-like remnants become actual holes.
    if 0.2126 * r + 0.7152 * g + 0.0722 * b >= 140:
        return 0
    return 1


def palette_image(size, indices):
    image = Image.frombytes("P", size, bytes(indices))
    image.putpalette(bytes([0, 0, 0, 0, 0, 0, *RED]))
    image.info["transparency"] = bytes([0, 255, 255])
    return image


def verify(path):
    with Image.open(path) as image:
        counts = Counter(image.convert("RGBA").get_flattened_data())
        assert set(counts) <= ALLOWED, f"Unexpected pixel states in {path.name}"
        return {
            "size": list(image.size),
            "black_pixels": counts[(0, 0, 0, 255)],
            "red_pixels": counts[(*RED, 255)],
            "transparent_pixels": counts[(0, 0, 0, 0)],
            "opaque_white_pixels": 0,
            "pixel_states": len(counts),
        }


def label_layers(mapped):
    """Nearest-neighbour label size, split into black-only and red-only layers."""
    height = round(mapped.height * LABEL_LOGO_WIDTH / mapped.width)
    art = mapped.resize((LABEL_LOGO_WIDTH, height), Image.Resampling.NEAREST)
    indices = art.tobytes()
    black = palette_image(art.size, [1 if i == 1 else 0 for i in indices])
    red = palette_image(art.size, [2 if i == 2 else 0 for i in indices])
    return art, black, red


def png_base64(image):
    import base64
    import io
    buffer = io.BytesIO()
    image.save(buffer, format="PNG", bits=2, optimize=True)
    return base64.b64encode(buffer.getvalue()).decode("ascii")


def label_module(mapped):
    art, black, red = label_layers(mapped)
    return (
        "/* Generated by script/build_brand_assets.py from the approved plant. Do not edit. */\n"
        "/** Nearest-neighbour layers of the original logo: one per print ink. */\n"
        "export const TanLabelLogo = {\n"
        f"  width: {art.width},\n"
        f"  height: {art.height},\n"
        f'  black: "data:image/png;base64,{png_base64(black)}",\n'
        f'  red: "data:image/png;base64,{png_base64(red)}",\n'
        "} as const\n"
    )


def verify_label(mapped):
    """The two layers must partition the mapped art exactly, one ink each."""
    import base64
    import io
    import re
    art, _, _ = label_layers(mapped)
    text = LABEL_LOGO.read_text()
    assert text == label_module(mapped), "labels/logo.ts is stale; rebuild it"
    layers = {}
    for ink in ["black", "red"]:
        data = re.search(ink + r': "data:image/png;base64,([^"]+)"', text).group(1)
        with Image.open(io.BytesIO(base64.b64decode(data))) as image:
            layers[ink] = image.convert("RGBA")
    expected = art.convert("RGBA").get_flattened_data()
    black = layers["black"].get_flattened_data()
    red = layers["red"].get_flattened_data()
    assert set(black) <= {(0, 0, 0, 0), (0, 0, 0, 255)}, "black layer has other states"
    assert set(red) <= {(0, 0, 0, 0), (*RED, 255)}, "red layer has other states"
    for e, b, r in zip(expected, black, red):
        assert (r if r[3] else b) == e, "label layers do not reproduce the master"


def verify_studio(mapped, icon):
    """Studio copies must equal the mapped master or its nearest-neighbour icons exactly."""
    def same(image, expected, label):
        rgba = image.convert("RGBA")
        assert set(rgba.get_flattened_data()) <= ALLOWED, f"Unexpected pixel states in {label}"
        assert rgba.size == expected.size, f"Unexpected size in {label}"
        assert rgba.tobytes() == expected.convert("RGBA").tobytes(), f"{label} differs from the master"

    for name in ["tan-logo.png", "tan-logo.webp"]:
        with Image.open(STUDIO / name) as image:
            same(image, mapped, name)
    for size, name in STUDIO_ICONS:
        with Image.open(STUDIO / name) as image:
            same(image, icon(size), name)
    with Image.open(STUDIO / "favicon.ico") as ico:
        assert sorted(ico.info["sizes"]) == [(size, size) for size in ICO_SIZES], "favicon.ico frames"
        for size in ICO_SIZES:
            same(ico.ico.getimage((size, size)), icon(size), f"favicon.ico {size}px")


def main():
    check = "--check" in sys.argv
    with Image.open(SOURCE) as source:
        source = source.convert("RGBA")
        mapped = palette_image(source.size, map(mapped_index, source.get_flattened_data()))
    # Nearest-neighbour delivery sizes preserve the same three pixel states.
    def icon(size):
        art = mapped.copy()
        art.thumbnail((size, size), Image.Resampling.NEAREST)
        canvas = palette_image((size, size), [0] * size * size)
        canvas.paste(art, ((size - art.width) // 2, (size - art.height) // 2))
        return canvas

    if not check:
        mapped.save(ASSETS / "tan-logo.png", bits=2, optimize=True)
        mapped.convert("RGBA").save(ASSETS / "tan-logo.webp", "WEBP", lossless=True, method=6)
        for size, name in [(128, "tan-favicon.png"), (180, "tan-touch-icon.png")]:
            icon(size).save(ASSETS / name, bits=2, optimize=True)
        # Studio delivery copies of the same master; never part of the public proof.
        mapped.save(STUDIO / "tan-logo.png", bits=2, optimize=True)
        mapped.convert("RGBA").save(STUDIO / "tan-logo.webp", "WEBP", lossless=True, method=6)
        for size, name in STUDIO_ICONS:
            icon(size).save(STUDIO / name, bits=2, optimize=True)
        # Every ICO frame is supplied explicitly so Pillow never resamples (antialiases) one.
        frames = [icon(size).convert("RGBA") for size in ICO_SIZES]
        frames[-1].save(STUDIO / "favicon.ico", format="ICO",
                        sizes=[(size, size) for size in ICO_SIZES], append_images=frames[:-1])
    if not check:
        LABEL_LOGO.write_text(label_module(mapped))
    verify_studio(mapped, icon)
    verify_label(mapped)
    names = ["tan-logo.png", "tan-logo.webp", "tan-favicon.png", "tan-touch-icon.png"]
    report = {
        "source": str(SOURCE.relative_to(ROOT)),
        "source_sha256": hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
        "method": "Deterministic pixel classification; original dimensions and positions retained",
        "rules": {"alpha_cutoff": 128, "pale_luminance_cutoff": 140,
                  "red": "r >= 80, r-g >= 35, r-b >= 25, r > 1.35*g, r > 1.35*b"},
        "ink_black": "#000000", "ink_red": "#B6151B", "alpha_values": [0, 255],
        "exports": {name: verify(ASSETS / name) for name in names},
    }
    with Image.open(ASSETS / "tan-logo.png") as result:
        assert result.size == mapped.size
        assert result.convert("RGBA").tobytes() == mapped.convert("RGBA").tobytes()
    with Image.open(ASSETS / "tan-logo.webp") as web:
        assert web.convert("RGBA").tobytes() == mapped.convert("RGBA").tobytes()
    target = ROOT / "docs/brand/palette-proof.json"
    if not check:
        target.write_text(json.dumps(report, indent=2) + "\n")
    else:
        assert json.loads(target.read_text()) == report
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
